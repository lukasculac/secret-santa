#!/usr/bin/env node
/**
 * Secret Santa draw generator.
 *
 * Run this ONCE. It picks a random valid assignment and writes `draw.js`,
 * where each person's giftee is encrypted under a key derived from their
 * own name. Commit the generated draw.js and push.
 *
 * Usage:
 *   node generate.mjs                        # uses the NAMES below
 *   node generate.mjs Ana Bob Cveta Dino     # or pass names as arguments
 *
 * No dependencies. Needs Node 18+ (uses global Web Crypto).
 */

import { writeFileSync } from 'node:fs';
import { randomInt, randomBytes } from 'node:crypto';

// ---------------------------------------------------------------- the group
const NAMES = ['Lule', 'Trdo', 'Shuljo', 'Erik', 'Matej'];

// PBKDF2 rounds. High enough to make bulk peeking tedious, low enough
// that an old phone still unwraps instantly.
const ITERATIONS = 210000;

// ------------------------------------------------------------------ helpers

/** Canonical form of a name, so generator and browser derive the same key. */
const normalize = (s) =>
  s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().trim().replace(/\s+/g, ' ');

const b64 = (bytes) => Buffer.from(bytes).toString('base64');

/**
 * Sattolo's algorithm: a uniformly random cyclic permutation.
 *
 * This is deliberately not a plain shuffle. A cyclic permutation gives one
 * single gift chain covering everyone (A->B->C->D->E->A), which guarantees
 * two things a naive shuffle does not:
 *   - nobody ever draws themselves, and
 *   - no two people draw each other (no boring A<->B mutual pair).
 * Uses crypto-grade randomness, not Math.random.
 */
function cyclicPermutation(items) {
  const a = [...items];
  for (let i = a.length - 1; i > 0; i--) {
    const j = randomInt(i); // 0 <= j < i  (strictly less than i -> single cycle)
    [a[i], a[j]] = [a[j], a[i]];
  }
  // a[k] receives a gift from the person standing at a[k-1]; chain it up.
  const pairs = new Map();
  for (let k = 0; k < a.length; k++) {
    pairs.set(a[k], a[(k + 1) % a.length]);
  }
  return pairs;
}

/** Opaque per-person lookup id, so draw.js has no readable name->name mapping. */
async function personId(name, pepper) {
  const data = new TextEncoder().encode(`${pepper}:${normalize(name)}`);
  const hash = await crypto.subtle.digest('SHA-256', data);
  return Buffer.from(hash).toString('hex').slice(0, 32);
}

/** Derive an AES-256-GCM key from a person's own name. */
async function deriveKey(name, salt, pepper) {
  const material = await crypto.subtle.importKey(
    'raw',
    new TextEncoder().encode(`${pepper}:${normalize(name)}`),
    'PBKDF2',
    false,
    ['deriveKey'],
  );
  return crypto.subtle.deriveKey(
    { name: 'PBKDF2', salt, iterations: ITERATIONS, hash: 'SHA-256' },
    material,
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt', 'decrypt'],
  );
}

// --------------------------------------------------------------------- main

const names = process.argv.length > 2 ? process.argv.slice(2) : NAMES;

if (names.length < 3) {
  console.error('Need at least 3 people for a secret santa.');
  process.exit(1);
}
const seen = new Set(names.map(normalize));
if (seen.size !== names.length) {
  console.error('Two people normalize to the same name. Add a last initial to tell them apart.');
  process.exit(1);
}

const pepper = randomBytes(16).toString('hex');
const assignment = cyclicPermutation(names);

const gifts = {};
for (const [giver, giftee] of assignment) {
  const salt = randomBytes(16);
  const iv = randomBytes(12);
  const key = await deriveKey(giver, salt, pepper);
  const ct = await crypto.subtle.encrypt(
    { name: 'AES-GCM', iv },
    key,
    new TextEncoder().encode(giftee),
  );
  gifts[await personId(giver, pepper)] = { s: b64(salt), n: b64(iv), c: b64(ct) };
}

// Sort by opaque id so the key order in the file leaks nothing about the chain.
const ordered = {};
for (const id of Object.keys(gifts).sort()) ordered[id] = gifts[id];

const payload = {
  v: 1,
  drawnAt: new Date().toISOString(),
  pepper,
  iter: ITERATIONS,
  roster: names,
  gifts: ordered,
};

writeFileSync(
  new URL('./draw.js', import.meta.url),
  `// Generated by generate.mjs on ${payload.drawnAt}
// Each entry is a giftee name encrypted with a key derived from the giver's
// own name. Re-run \`node generate.mjs\` to draw again. Do not hand-edit.
window.SANTA_DRAW = ${JSON.stringify(payload, null, 2)};
`,
);

console.log(`\n  Drew ${names.length} names into one gift chain.`);
console.log('  Wrote draw.js  (encrypted - even you cannot read it at a glance)\n');
console.log('  Next:  git add -A && git commit -m "new draw" && git push\n');
